async function seed() {
  const connection = await mysql.createConnection({
    host: process.env.DB_HOST || 'localhost',
    port: process.env.DB_PORT || 3306,
    user: process.env.DB_USER || 'root',
    password: process.env.DB_PASSWORD || '',
    database: process.env.DB_NAME || 'what_to_eat',
  });

  console.log('数据库连接成功，开始插入种子数据...');

  // 清空现有数据
  await connection.execute('DELETE FROM foods WHERE is_custom = 0');

  const sql = `INSERT INTO foods (name, category, calories, protein, carbs, fat, unit, is_custom)
               VALUES (?, ?, ?, ?, ?, ?, ?, 0)`;

  let inserted = 0;
  for (const food of foods) {
    try {
      await connection.execute(sql, food);
      inserted++;
    } catch (err) {
      console.error(`插入失败: ${food[0]}`, err.message);
    }
  }

  console.log(`种子数据插入完成！共 ${inserted} 条记录（总计 ${foods.length} 条）`);
  await connection.end();
  process.exit(0);
}

seed().catch(err => {
  console.error('种子数据执行失败:', err);
  process.exit(1);
});
